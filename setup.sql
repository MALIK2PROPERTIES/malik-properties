-- MALIK PROPERTIES: run this in Supabase SQL Editor.
-- This creates a separate table so property enquiries do not mix with MALIK ONLINE SERVICES applications.
create table if not exists public.property_enquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  intent text not null check (intent in ('BUY','SELL')),
  district text not null,
  tehsil text,
  village text,
  property_type text not null,
  area numeric,
  area_unit text,
  budget_min numeric,
  budget_max numeric,
  gata_no text,
  khasra_no text,
  asking_price numeric,
  negotiable text,
  name text not null,
  mobile text not null,
  whatsapp text,
  email text,
  address text,
  details text
);
alter table public.property_enquiries enable row level security;

-- Public visitors can submit enquiries, but cannot read them.
drop policy if exists "Public can submit property enquiries" on public.property_enquiries;
create policy "Public can submit property enquiries"
on public.property_enquiries for insert
to anon, authenticated
with check (true);

-- Only signed-in users can view/manage records. Create only your own admin user in Supabase Auth
-- and keep public sign-ups disabled in Supabase Authentication settings.
drop policy if exists "Admins can view property enquiries" on public.property_enquiries;
create policy "Admins can view property enquiries"
on public.property_enquiries for select
to authenticated
using (true);

drop policy if exists "Admins can update property enquiries" on public.property_enquiries;
create policy "Admins can update property enquiries"
on public.property_enquiries for update
to authenticated
using (true) with check (true);

drop policy if exists "Admins can delete property enquiries" on public.property_enquiries;
create policy "Admins can delete property enquiries"
on public.property_enquiries for delete
to authenticated
using (true);

grant usage on schema public to anon, authenticated;
grant insert on public.property_enquiries to anon, authenticated;
grant select, update, delete on public.property_enquiries to authenticated;
grant usage, select on sequence public.property_enquiries_id_seq to anon, authenticated;
